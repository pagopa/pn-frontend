// simulates the server-side search and the lastKey pagination of the API
export const getInstitutionsResponse = ({
  search,
  limit = 10,
  lastKey,
}: GetInstitutionsParams): InstitutionsResponse => {
  const normalizedSearch = search?.toLowerCase() ?? '';
  const filtered = institutionsList.filter(
    (institution) =>
      institution.institutionName.toLowerCase().includes(normalizedSearch) ||
      institution.institutionTaxCode.toLowerCase().includes(normalizedSearch)
  );
  const start = lastKey ? Number(lastKey) : 0;
  const end = start + limit;
  return {
    items: filtered.slice(start, end),
    lastKey: end < filtered.length ? String(end) : undefined,
  };
};
